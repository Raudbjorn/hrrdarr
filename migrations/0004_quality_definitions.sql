-- Domain facts inventoried at Sonarr76c684e / Radarrc90668a Quality.cs and
-- QualityDefinitionLimits.cs. Independently authored storage, not upstream schema.
CREATE TABLE quality_definitions (
    media_type TEXT NOT NULL CHECK (media_type IN ('tv','movies')),
    quality_id INTEGER NOT NULL CHECK (quality_id >= 0),
    name TEXT NOT NULL,
    source TEXT NOT NULL,
    resolution INTEGER NOT NULL CHECK (resolution >= 0),
    modifier TEXT,
    weight INTEGER NOT NULL CHECK (weight > 0),
    group_name TEXT,
    default_min REAL,
    default_max REAL,
    default_preferred REAL,
    title TEXT NOT NULL CHECK (length(trim(title)) BETWEEN 1 AND 100),
    min_size REAL,
    max_size REAL,
    preferred_size REAL,
    PRIMARY KEY (media_type, quality_id),
    CHECK (min_size IS NULL OR min_size BETWEEN 0 AND CASE media_type WHEN 'tv' THEN 1000 ELSE 2000 END),
    CHECK (max_size IS NULL OR max_size BETWEEN 0 AND CASE media_type WHEN 'tv' THEN 1000 ELSE 2000 END),
    CHECK (preferred_size IS NULL OR preferred_size BETWEEN 0 AND CASE media_type WHEN 'tv' THEN 1000 ELSE 2000 END),
    CHECK (min_size IS NULL OR max_size IS NULL OR min_size <= max_size),
    CHECK (min_size IS NULL OR preferred_size IS NULL OR min_size <= preferred_size),
    CHECK (preferred_size IS NULL OR max_size IS NULL OR preferred_size <= max_size)
);
CREATE TRIGGER quality_identity_immutable BEFORE UPDATE OF media_type,quality_id,name,source,resolution,modifier,weight,group_name,default_min,default_max,default_preferred ON quality_definitions
BEGIN SELECT RAISE(ABORT, 'quality catalog identity and defaults are immutable'); END;

-- Persisted profile item/group foundation. Ranking/cutoff/scoring policy arrives separately.
CREATE TABLE quality_profiles (
    id INTEGER PRIMARY KEY,
    media_type TEXT NOT NULL CHECK (media_type IN ('tv','movies')),
    name TEXT NOT NULL CHECK (length(trim(name)) BETWEEN 1 AND 100),
    UNIQUE (id, media_type),
    UNIQUE (media_type, name)
);
CREATE TABLE quality_profile_groups (
    id INTEGER PRIMARY KEY,
    profile_id INTEGER NOT NULL REFERENCES quality_profiles(id) ON DELETE CASCADE,
    name TEXT NOT NULL CHECK (length(trim(name)) BETWEEN 1 AND 100),
    position INTEGER NOT NULL CHECK (position >= 0),
    allowed INTEGER NOT NULL CHECK (allowed IN (0,1)),
    UNIQUE (id, profile_id),
    UNIQUE (profile_id, position)
);
CREATE TABLE quality_profile_items (
    profile_id INTEGER NOT NULL,
    media_type TEXT NOT NULL,
    quality_id INTEGER NOT NULL,
    group_id INTEGER,
    position INTEGER NOT NULL CHECK (position >= 0),
    allowed INTEGER NOT NULL CHECK (allowed IN (0,1)),
    min_size REAL,
    max_size REAL,
    preferred_size REAL,
    PRIMARY KEY (profile_id, quality_id),
    FOREIGN KEY (profile_id, media_type) REFERENCES quality_profiles(id, media_type) ON DELETE CASCADE,
    FOREIGN KEY (media_type, quality_id) REFERENCES quality_definitions(media_type, quality_id),
    FOREIGN KEY (group_id, profile_id) REFERENCES quality_profile_groups(id, profile_id),
    CHECK (min_size IS NULL OR min_size BETWEEN 0 AND CASE media_type WHEN 'tv' THEN 1000 ELSE 2000 END),
    CHECK (max_size IS NULL OR max_size BETWEEN 0 AND CASE media_type WHEN 'tv' THEN 1000 ELSE 2000 END),
    CHECK (preferred_size IS NULL OR preferred_size BETWEEN 0 AND CASE media_type WHEN 'tv' THEN 1000 ELSE 2000 END),
    CHECK (min_size IS NULL OR max_size IS NULL OR min_size <= max_size),
    CHECK (min_size IS NULL OR preferred_size IS NULL OR min_size <= preferred_size),
    CHECK (preferred_size IS NULL OR max_size IS NULL OR preferred_size <= max_size)
);
CREATE UNIQUE INDEX quality_profile_item_position ON quality_profile_items(profile_id,coalesce(group_id,0),position);
CREATE INDEX quality_profile_propagation ON quality_profile_items(media_type,quality_id);
